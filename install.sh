#!/bin/bash
# disktwin - root part of the installation: packages, commands, config, smartd and linger.
#   sudo ./install.sh
# Then, as your user (no sudo): ./install-user.sh
set -euo pipefail
cd "$(dirname "$0")"
[[ $EUID -eq 0 ]] || { echo "Run with sudo: sudo ./install.sh" >&2; exit 1; }
[[ -f disktwin.conf ]] || { echo "Missing disktwin.conf (copy config.example and fill it in)" >&2; exit 1; }
# shellcheck source=/dev/null
source ./disktwin.conf

echo "== Packages: rsync, inotify-tools, smartmontools, libnotify-bin =="
apt-get update -qq
DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends rsync inotify-tools smartmontools libnotify-bin

echo "== Commands in /usr/local/bin, config in /etc/disktwin.conf =="
install -m 755 bin/* /usr/local/bin/
install -m 644 disktwin.conf /etc/disktwin.conf
install -d -o "$NOTIFY_USER" -g "$NOTIFY_USER" -m 775 "$ALERTS_DIR" "$ALERTS_DIR/pending" "$ALERTS_DIR/seen"

echo "== smartd =="
[[ -f /etc/smartd.conf && ! -f /etc/smartd.conf.orig ]] && cp /etc/smartd.conf /etc/smartd.conf.orig
EXEC="-m root -M exec /usr/local/bin/disktwin-alert"
{
  echo "# Generated by disktwin/install.sh (original in /etc/smartd.conf.orig)"
  for d in "${SMART_DISKS[@]}"; do
    if [[ $d == *nvme* ]]; then echo "$d $SMART_OPTS_NVME $EXEC"
    else echo "$d $SMART_OPTS_ATA $EXEC"; fi
  done
} > /etc/smartd.conf
systemctl enable smartmontools 2>/dev/null || systemctl enable smartd
systemctl restart smartmontools 2>/dev/null || systemctl restart smartd

echo "== linger: $NOTIFY_USER's services run even when not logged in =="
loginctl enable-linger "$NOTIFY_USER"

echo "== SMART status =="
for d in "${SMART_DISKS[@]}"; do
  printf '%s\n   ' "$d"; smartctl -H "$d" | grep -iE 'overall-health|SMART Health Status' || echo "(no result)"
done

echo "== Test notification =="
if [[ ${DISKTWIN_LANG:-auto} == es || ( ${DISKTWIN_LANG:-auto} == auto && ${LANG:-} == es* ) ]]; then
  /usr/local/bin/disktwin-alert -k test "disktwin: alerta de prueba" "Si ves esto, las alertas funcionan. Bórrala con: disktwin-alerts --ok"
else
  /usr/local/bin/disktwin-alert -k test "disktwin test alert" "If you can see this, alerts work. Clear it with: disktwin-alerts --ok"
fi
echo "Done. Now, as $NOTIFY_USER and without sudo: ./install-user.sh"
